def noise(s):
    if R.random() < 0.25:
        a, b = R.choice(STT)
        if a in s:
            s = s.replace(a, b, 1)
    r = R.random()
    if r < 0.12:
        s = s.replace(' ', '')
    elif r < 0.2:
        w = s.split(' ')
        if len(w) > 2:
            i = R.randrange(len(w) - 1); w[i] += w.pop(i + 1)
        s = ' '.join(w)
    elif r < 0.24:
        s = s.replace(' ', '  ', 1)
    if R.random() < 0.03 and len(s) > 4:          # 글자 하나 빠짐
        i = R.randrange(len(s)); s = s[:i] + s[i + 1:]
    if R.random() < 0.03:
        s = s + R.choice(['ㅋㅋ', 'ㅎㅎ', ' ㅋㅋㅋ', ' ㅠ'])
    return s.strip()



