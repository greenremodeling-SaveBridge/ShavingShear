def josa(s):
    """'전력#이/가' → '전력이' (받침 보고 고른다)"""
    def f(m):
        w, a, b = m.group(1), m.group(2), m.group(3)
        c = w[-1] if w else ''
        if '가' <= c <= '힣':
            jong = (ord(c) - 0xAC00) % 28
            use = a if jong and not (a.startswith('으로') and jong == 8) else b
        else:
            use = a
        return w + use
    return _re.sub(r'(\S*?)#([가-힣]*)/([가-힣]*)', f, s)


