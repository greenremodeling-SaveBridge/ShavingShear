def held(x):
    return zlib.crc32(x.encode()) % 5 == 0


def P(lst):
    """낱말 고르기 — 학습 때는 빼 둔 것(held)을 안 쓰고, fresh 때는 빼 둔 것을 쓴다"""
    if len(lst) >= 5:
        tr = [x for x in lst if not held(x)]
        te = [x for x in lst if held(x)]
        if MODE == 'train' and tr and not os.environ.get('SA_ALL'):
            lst = tr
        elif MODE == 'fresh' and te and R.random() < 0.7:
            lst = te
    return R.choice(lst)


